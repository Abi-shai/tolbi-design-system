/**
 * Generates components/BrandPattern/tile.ts from the raw stamp in
 * scripts/brand-pattern-raw/.
 *
 *   npm run brand-pattern
 *
 * WHY a generator rather than committing the Figma export: the export of
 * `Pattern — Kaleidoscope` (node 9892:11986) is one flattened vector of 7 680
 * paths and 23 MB, and it is not 2D-periodic — there is exactly one exact
 * translational symmetry in the whole sheet. It cannot be shipped and it cannot
 * be tiled. What it *is* is 480 stamps of a single 11-path drawing at 0° and
 * 180°, on a lattice. This lays that one drawing back out on the measured
 * lattice and closes it into a tile, which is 22 KB and repeats anywhere.
 *
 * Every constant below is measured off the specimen — see
 * scripts/brand-pattern-raw/README.md for the numbers and how they were taken,
 * and docs/adr/0035 for the two places this deliberately rounds them.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '..')
const RAW = join(HERE, 'brand-pattern-raw/kaleidoscope-stamp.svg')
const OUT = join(ROOT, 'components/BrandPattern/tile.ts')

/* ── the lattice, measured ──────────────────────────────────────────────── */

/** Column pitch. 16 columns across the specimen's 3538. */
const PITCH = 227
/** Vertical step between row pairs. 12 pairs across the specimen's 1769. */
const PAIR = 155.19
/** The 0° row of a pair sits this far below and right of its 180° row. */
const INNER_V = 32.5
const INNER_U = 139.8
/**
 * Horizontal shift per row pair. Measured 83.4 — but a tile has to close, and
 * `6 × SHIFT ≡ 0 (mod 2 × PITCH)` admits only 227/3. It moves the diagonal the
 * rosettes run along by 2.2°, which is the price of the tile being 931 tall
 * rather than 2483 (ADR-0035).
 */
const SHIFT = PITCH / 3
/**
 * Six pairs is the specimen's own exact period — the single translational
 * symmetry it has is `(29.33, 931.17)`, and `6 × PAIR = 931.14`.
 */
const PAIRS = 6
/** Two columns, because the doubling alternates across them. */
const COLS = 2

/**
 * Every other pair doubles every other column: the stamp is drawn twice at the
 * same point, so its 20% ink composites to 36%. That is the whole of the
 * specimen's tonal variation — there is no second colour and no second opacity.
 */
const doubled = (pair, col) => pair % 2 === 0 && col % 2 === 0

/* ── the stamp ──────────────────────────────────────────────────────────── */

const raw = readFileSync(RAW, 'utf8')
const marks = [...raw.matchAll(/<path\s+d="([^"]+)"/g)].map((m) => m[1])
if (marks.length < 2) throw new Error(`${RAW}: expected the stamp's paths, found ${marks.length}`)

const box = raw.match(/viewBox="0 0 ([\d.]+) ([\d.]+)"/)
if (!box) throw new Error(`${RAW}: expected a viewBox anchored at 0 0`)
const [stampW, stampH] = [Number(box[1]), Number(box[2])]

/**
 * The anchor is the centroid of the outline path's control points — the point
 * the 480 instances were measured against, and therefore the point a 180° stamp
 * turns about. It is recomputed, not stored, so a re-export cannot shift the
 * pattern without the outline itself moving.
 */
function centroid(d) {
  const n = d.match(/-?\d+(?:\.\d+)?/g).map(Number)
  let sx = 0, sy = 0, c = 0
  for (let i = 0; i + 1 < n.length; i += 2) { sx += n[i]; sy += n[i + 1]; c++ }
  return [sx / c, sy / c]
}
const [anchorX, anchorY] = centroid(marks[0])

/* ── the tile ───────────────────────────────────────────────────────────── */

const TILE_W = PITCH * COLS
const TILE_H = PAIR * PAIRS

const stamps = []
for (let p = 0; p < PAIRS; p++) {
  for (let c = 0; c < COLS; c++) {
    const u = p * SHIFT + c * PITCH
    const v = p * PAIR
    for (let n = doubled(p, c) ? 2 : 1; n > 0; n--) {
      stamps.push([u, v, 180])
      stamps.push([u + INNER_U, v + INNER_V, 0])
    }
  }
}

/**
 * Seamless by construction: every stamp is wrapped into the tile, then drawn
 * again at each neighbouring offset it still reaches into. The tile clips, so a
 * stamp cut by an edge arrives whole on the other side. Nothing has to line up
 * for this to work, which is why the lattice can be rounded at all.
 */
const reach = Math.hypot(stampW, stampH)
const placements = []
for (const [u, v, rot] of stamps) {
  const u0 = ((u % TILE_W) + TILE_W) % TILE_W
  const v0 = ((v % TILE_H) + TILE_H) % TILE_H
  for (let dx = -1; dx <= 1; dx++) {
    for (let dy = -1; dy <= 1; dy++) {
      const x = u0 + dx * TILE_W
      const y = v0 + dy * TILE_H
      if (x < -reach || x > TILE_W + reach || y < -reach || y > TILE_H + reach) continue
      placements.push([x, y, rot])
    }
  }
}

const round = (n) => Number(n.toFixed(2))

writeFileSync(
  OUT,
  `/**
 * GENERATED by scripts/generate-brand-pattern.mjs — do not edit by hand.
 * Run \`npm run brand-pattern\` after changing scripts/brand-pattern-raw/.
 *
 * Source: Figma \`00 — Core Brand Visual Identity\` — \`Pattern — Kaleidoscope\`
 * (node 9892:11986). Geometry only: no colour, no opacity, no size. The
 * component owns all three.
 */

/** The repeating unit, in the stamp's own units. Tiles on any surface. */
export const tile = { width: ${round(TILE_W)}, height: ${round(TILE_H)} } as const

/**
 * The stamp: the Tolbi mark, twice, as the brand sheet draws it. \`anchor\` is
 * the point a 180° placement turns about.
 */
export const stamp = {
  width: ${round(stampW)},
  height: ${round(stampH)},
  anchorX: ${round(anchorX)},
  anchorY: ${round(anchorY)},
} as const

/** The stamp's paths, exactly as Figma drew them. */
export const marks: readonly string[] = [
${marks.map((d) => `  '${d}',`).join('\n')}
]

/**
 * \`[x, y, rotation]\` per stamp — ${stamps.length} on the lattice, plus the copies that
 * carry them across the tile's edges. A repeated triple is the specimen's
 * doubled ink, not a mistake.
 */
export const placements: readonly (readonly [number, number, number])[] = [
${placements.map(([x, y, r]) => `  [${round(x)}, ${round(y)}, ${r}],`).join('\n')}
]
`,
)

console.log(
  `tile ${round(TILE_W)} × ${round(TILE_H)}   ${marks.length} paths   ` +
  `${stamps.length} stamps → ${placements.length} placements`,
)
