/**
 * Generates components/Flag/registry.ts from country-flag-icons (MIT), the
 * subset listed in flags.manifest.txt next to this script (ADR-0085).
 *
 * Like the icons (ADR-0004), the set is generated, never hand-written: add a
 * code to the manifest and run `npm run flags`. Each drawing is kept whole —
 * its viewBox and its shapes — and inlined by `Flag`; the drawings carry no
 * `id`, so two flags on one page cannot reach into each other's defs (the
 * script fails if one ever does).
 *
 *   npm run flags
 */
import { readFileSync, writeFileSync, copyFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '..')
const SRC = join(ROOT, 'node_modules/country-flag-icons/3x2')
const OUT = join(ROOT, 'components/Flag/registry.ts')
const version = JSON.parse(readFileSync(join(ROOT, 'node_modules/country-flag-icons/package.json'), 'utf8')).version

const codes = readFileSync(join(HERE, 'flags.manifest.txt'), 'utf8')
  .split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('#'))

const dupes = codes.filter((c, i) => codes.indexOf(c) !== i)
if (dupes.length) throw new Error(`flags.manifest.txt repeats ${dupes.join(', ')}`)
const bad = codes.filter(c => !/^[A-Z]{2}$/.test(c))
if (bad.length) throw new Error(`Not ISO 3166-1 alpha-2 codes: ${bad.join(', ')}`)

const entries = codes.sort().map(code => {
  let svg
  try { svg = readFileSync(join(SRC, `${code}.svg`), 'utf8') } catch {
    throw new Error(`No flag for ${code} in country-flag-icons@${version}`)
  }
  if (/\sid=/.test(svg)) throw new Error(`${code}.svg carries an id — inlined twice, it would collide`)
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1]
  if (!viewBox) throw new Error(`${code}.svg has no viewBox`)
  const body = svg.slice(svg.indexOf('>', svg.indexOf('<svg')) + 1, svg.lastIndexOf('</svg>')).replace(/\s*\n\s*/g, '').trim()
  return `  ${code}: { viewBox: '${viewBox}', body: ${JSON.stringify(body)} },`
})

writeFileSync(OUT, `/**
 * GENERATED by scripts/generate-flags.mjs — do not edit by hand.
 * Run \`npm run flags\` after changing scripts/flags.manifest.txt.
 *
 * Source: country-flag-icons ${version} (MIT), 3:2 drawings — see LICENSE-country-flag-icons.
 */
export const flags = {
${entries.join('\n')}
} as const

/** An ISO 3166-1 alpha-2 code the package carries a flag for. */
export type FlagCode = keyof typeof flags
`)
copyFileSync(join(ROOT, 'node_modules/country-flag-icons/LICENSE'), join(ROOT, 'components/Flag/LICENSE-country-flag-icons'))
console.log(`${codes.length} flags → components/Flag/registry.ts`)
