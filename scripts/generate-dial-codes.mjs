/**
 * Generates components/PhoneField/dialCodes.ts.
 *
 *   npm run dial-codes
 *
 * WHY generated: dial codes are reference data, and 245 numeric codes written by
 * hand would ship errors nobody would catch until a producer could not be
 * reached. Both inputs are authoritative and already on the machine:
 *
 *   - the codes come from `libphonenumber-js`, which carries Google's
 *     libphonenumber metadata;
 *   - the French country names come from `Intl.DisplayNames`, i.e. the CLDR data
 *     built into Node.
 *
 * Nothing here is transcribed. Same contract as the icon generator: the source
 * is a package, the output is committed, and the package stays a devDependency.
 *
 * Scope note: the design system carries the complete reference set. Which
 * subset a given form offers is a product decision, made by passing
 * `countries` to PhoneField — the design system does not encode business
 * geography.
 */
import { writeFileSync, readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { getCountries, getCountryCallingCode } from 'libphonenumber-js'

const HERE = dirname(fileURLToPath(import.meta.url))
const ROOT = join(HERE, '..')
const OUT = join(ROOT, 'components/PhoneField/dialCodes.ts')

const version = JSON.parse(
  readFileSync(join(ROOT, 'node_modules/libphonenumber-js/package.json'), 'utf8'),
).version

const names = new Intl.DisplayNames(['fr'], { type: 'region' })
const collator = new Intl.Collator('fr', { sensitivity: 'base' })

const entries = getCountries()
  .map(iso => {
    const label = names.of(iso)
    // Skip anything CLDR cannot name in French — it would render as its raw
    // ISO code in the picker, which is worse than being absent.
    if (!label || label === iso) return null
    return { value: iso, dial: `+${getCountryCallingCode(iso)}`, label }
  })
  .filter(Boolean)
  .sort((a, b) => collator.compare(a.label, b.label))

const seen = new Set()
for (const e of entries) {
  if (seen.has(e.value)) throw new Error(`duplicate ISO code: ${e.value}`)
  if (!/^\+\d{1,4}$/.test(e.dial)) throw new Error(`suspect dial code for ${e.value}: ${e.dial}`)
  seen.add(e.value)
}

const pad = Math.max(...entries.map(e => e.dial.length))

writeFileSync(
  OUT,
  `/**
 * GENERATED by scripts/generate-dial-codes.mjs — do not edit by hand.
 * Run \`npm run dial-codes\` to refresh.
 *
 * Codes: libphonenumber-js ${version} (Google libphonenumber metadata).
 * French names: Intl.DisplayNames (CLDR), sorted with a French collator so
 * accented initials fall in the right place.
 *
 * ${entries.length} entries — the complete reference set. Choosing which of them a
 * form offers is a product decision: pass \`countries\` to PhoneField.
 *
 * This is reference data only. The design system does not parse, validate or
 * format phone numbers — that is libphonenumber's job, in the product.
 */
import type { DialCode } from './PhoneField.vue'

export const dialCodes: readonly DialCode[] = [
${entries
  .map(e => `  { value: '${e.value}', dial: '${e.dial}',${' '.repeat(pad - e.dial.length)} label: ${JSON.stringify(e.label)} },`)
  .join('\n')}
]

/** Look up one entry by ISO 3166-1 alpha-2 code. */
export function dialCodeFor(iso: string): DialCode | undefined {
  return dialCodes.find(c => c.value === iso.toUpperCase())
}

/**
 * The entries for \`isoCodes\`, in the order given — for a form that wants a
 * short, ordered list rather than all ${entries.length}. Unknown codes are dropped.
 */
export function dialCodesFor(isoCodes: readonly string[]): DialCode[] {
  return isoCodes.map(iso => dialCodeFor(iso)).filter((c): c is DialCode => Boolean(c))
}
`,
)

console.log(`${entries.length} indicatifs générés depuis libphonenumber-js@${version}`)
console.log(`  ${getCountries().length - entries.length} écartés (non nommables en français)`)
